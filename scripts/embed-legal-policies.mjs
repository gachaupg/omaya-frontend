/**
 * Embeds content/legal markdown into the Next.js bundle for production (Docker/standalone).
 * Run before `next build` so legal pages work without runtime filesystem access.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const legalDir = path.join(root, "content", "legal");
const outFile = path.join(root, "lib", "legal", "embeddedPolicyMarkdown.ts");

const POLICIES = [
  { fileName: "OMAYA-Terms-of-Service-v1.5.md", legacy: "terms-of-service.md" },
  { fileName: "OMAYA-Privacy-Policy-v1.2.md" },
  { fileName: "OMAYA-Cookie-Policy-v1.1.md", legacy: "cookie-policy.md" },
  { fileName: "OMAYA-AML-KYC-Policy-v1.1.md", legacy: "aml-kyc-policy.md" },
  { fileName: "OMAYA-Risk-Disclosure-Statement-v1.1.md", legacy: "risk-disclosure-statement.md" },
  { fileName: "OMAYA-Law-Enforcement-Request-Guidelines-v1.1.md" },
  { fileName: "OMAYA-Payment-Policy-v1.1.md" },
  { fileName: "OMAYA-Referral-Program-Terms-v1.1.md" },
];

const embedded = {};

for (const policy of POLICIES) {
  const candidates = [policy.fileName, policy.legacy].filter(Boolean);
  let loaded = null;
  for (const name of candidates) {
    const filePath = path.join(legalDir, name);
    if (fs.existsSync(filePath)) {
      loaded = fs.readFileSync(filePath, "utf8");
      break;
    }
  }
  if (!loaded) {
    console.error(`[embed-legal-policies] Missing markdown for ${policy.fileName}`);
    process.exit(1);
  }
  embedded[policy.fileName] = loaded;
}

const banner = `/** Auto-generated by scripts/embed-legal-policies.mjs — do not edit manually */\n`;
const body = `export const EMBEDDED_POLICY_MARKDOWN: Record<string, string> = ${JSON.stringify(embedded)};\n`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, banner + body, "utf8");
console.log(`[embed-legal-policies] Wrote ${Object.keys(embedded).length} policies to lib/legal/embeddedPolicyMarkdown.ts`);
